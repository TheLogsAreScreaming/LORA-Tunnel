#!/usr/bin/env python3
"""Regenerate lora_tunnel_zero/recon_vendors.py from the firmware's vendor table.

The source of truth is lib/recon/src/dragon/vendor_prefixes.h, the same table the
Cardputer ADV and Heltec firmware compile in. Run from cardputer-zero/:
    python3 tools/sync_recon_data.py [--check]
"""

import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parents[1]
SOURCE = HERE.parent / "lib" / "recon" / "src" / "dragon" / "vendor_prefixes.h"
TARGET = HERE / "lora_tunnel_zero" / "recon_vendors.py"
ROW = re.compile(r'^\s*\{0x([0-9a-f]{6}),Family::(\w+),Confidence::(\w+),"((?:[^"\\]|\\.)*)"\},\s*$')


def render():
    rows = []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        match = ROW.match(line)
        if match:
            prefix, family, confidence, evidence = match.groups()
            rows.append((int(prefix, 16), family, confidence, evidence.replace('\\"', '"')))
    if len(rows) < 100 or [r[0] for r in rows] != sorted(r[0] for r in rows):
        raise SystemExit("Unexpected vendor table layout in %s" % SOURCE)
    out = ['"""Generated by tools/sync_recon_data.py from lib/recon/src/dragon/vendor_prefixes.h.',
           "",
           "Dragon Detector data, copyright (c) 2026 Valleytech Custom Solutions, MIT",
           "(lib/recon/LICENSE-DragonDetector). Registry facts were checked 2026-10-13",
           "against Wireshark's IEEE-derived manuf registry. Do not edit by hand.",
           '"""',
           "",
           "# (prefix, family, confidence, evidence), sorted by prefix.",
           "VENDOR_PREFIXES = ("]
    for prefix, family, confidence, evidence in rows:
        out.append("    (0x%06x, %r, %r, %r)," % (prefix, family, confidence, evidence))
    out.append(")")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("recon_vendors.py is stale; run tools/sync_recon_data.py", file=sys.stderr)
            return 1
        print("recon_vendors.py matches the firmware vendor table")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print("wrote", TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
